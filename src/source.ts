import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export const SOURCE_DIR = '.skillcast';
export const MARKER = 'generated by skillcast from';

export type Frontmatter = { fields: Map<string, string>; body: string };
export type Skill = { name: string; description: string; extra: Map<string, string>; body: string; file: string };
export type Source = { rules?: { body: string; file: string }; skills: Skill[] };

export class SourceError extends Error {}

export function normalize(text: string): string {
  return text.replace(/\r\n?/g, '\n').replace(/\s+$/, '') + '\n';
}

/** Parses a `---` frontmatter block of `key: value` lines. Values stay raw (quotes included). */
export function parseFrontmatter(text: string, file: string): Frontmatter | null {
  const t = text.replace(/\r\n?/g, '\n');
  if (!t.startsWith('---\n')) return null;
  const end = t.indexOf('\n---', 4);
  if (end < 0) throw new SourceError(`${file}: frontmatter is not closed with ---`);
  const fields = new Map<string, string>();
  for (const [i, line] of t.slice(4, end).split('\n').entries()) {
    if (!line.trim()) continue;
    const m = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!m) throw new SourceError(`${file}:${i + 2}: expected "key: value" in frontmatter, got "${line}"`);
    fields.set(m[1], m[2].trim());
  }
  return { fields, body: t.slice(end + 4).replace(/^\n+/, '') };
}

export function unquote(raw: string): string {
  if (raw.startsWith('"')) {
    try {
      return JSON.parse(raw);
    } catch {
      throw new SourceError(`invalid quoted value ${raw}`);
    }
  }
  if (raw.startsWith("'") && raw.endsWith("'")) return raw.slice(1, -1).replace(/''/g, "'");
  return raw;
}

const OPEN = /^<!--\s*only:([\w-]+)\s*-->\s*$/;
const CLOSE = /^<!--\s*\/only\s*-->\s*$/;

/** Keeps shared lines plus the blocks for `harness`; throws on unknown or unclosed blocks. */
export function selectBlocks(body: string, harness: string, known: string[], file: string): string {
  const out: string[] = [];
  let current: string | null = null;
  let openedAt = 0;
  for (const [i, line] of body.split('\n').entries()) {
    const open = OPEN.exec(line);
    if (open) {
      if (current) throw new SourceError(`${file}:${i + 1}: nested only-block inside only:${current}`);
      if (!known.includes(open[1])) throw new SourceError(`${file}:${i + 1}: unknown harness "${open[1]}" (known: ${known.join(', ')})`);
      current = open[1];
      openedAt = i + 1;
      continue;
    }
    if (CLOSE.test(line)) {
      if (!current) throw new SourceError(`${file}:${i + 1}: <!-- /only --> without an opening block`);
      current = null;
      continue;
    }
    if (!current || current === harness) out.push(line);
  }
  if (current) throw new SourceError(`${file}:${openedAt}: only:${current} block is never closed`);
  return normalize(out.join('\n').replace(/\n{3,}/g, '\n\n'));
}

const NAME = /^[a-z0-9][a-z0-9-]*$/;

export function loadSource(root: string): Source {
  const dir = join(root, SOURCE_DIR);
  if (!existsSync(dir)) throw new SourceError(`${SOURCE_DIR}/ not found; run "skillcast init" first`);
  const source: Source = { skills: [] };
  const rulesPath = join(dir, 'rules.md');
  if (existsSync(rulesPath)) source.rules = { body: normalize(readFileSync(rulesPath, 'utf8')), file: `${SOURCE_DIR}/rules.md` };
  const skillsDir = join(dir, 'skills');
  const files = existsSync(skillsDir) ? readdirSync(skillsDir).filter((f) => f.endsWith('.md')).sort() : [];
  const seen = new Map<string, string>();
  for (const f of files) {
    const file = `${SOURCE_DIR}/skills/${f}`;
    const fm = parseFrontmatter(readFileSync(join(skillsDir, f), 'utf8'), file);
    if (!fm) throw new SourceError(`${file}: missing frontmatter (needs name and description)`);
    const name = fm.fields.get('name') && unquote(fm.fields.get('name')!);
    const description = fm.fields.get('description') && unquote(fm.fields.get('description')!);
    if (!name) throw new SourceError(`${file}: frontmatter field "name" is missing`);
    if (!description) throw new SourceError(`${file}: frontmatter field "description" is missing`);
    if (!NAME.test(name)) throw new SourceError(`${file}: name "${name}" must be lowercase letters, digits and dashes`);
    if (seen.has(name)) throw new SourceError(`${file}: duplicate skill name "${name}" (also in ${seen.get(name)})`);
    if (`${name}.md` !== f) throw new SourceError(`${file}: name "${name}" must match the file name (${name}.md)`);
    seen.set(name, file);
    const extra = new Map([...fm.fields].filter(([k]) => k !== 'name' && k !== 'description'));
    source.skills.push({ name, description, extra, body: normalize(fm.body), file });
  }
  return source;
}
