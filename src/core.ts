import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { DEFAULT_ADAPTERS, plan, type Adapter } from './adapters';
import { loadSource, MARKER, normalize, parseFrontmatter, SOURCE_DIR, SourceError, unquote } from './source';

export type Problem = { file: string; kind: 'missing' | 'changed' | 'extra' | 'handwritten'; detail: string };

const isGenerated = (text: string) => text.includes(MARKER);
const read = (root: string, rel: string) => (existsSync(join(root, rel)) ? readFileSync(join(root, rel), 'utf8') : null);

/** Generated files currently on disk in the adapters' skill locations. */
function generatedOnDisk(root: string, adapters: Adapter[]): string[] {
  const found: string[] = [];
  for (const a of adapters) {
    const { dir, file, suffix } = a.skillGlob;
    if (!existsSync(join(root, dir))) continue;
    for (const entry of readdirSync(join(root, dir)).sort()) {
      const rel = file ? `${dir}/${entry}/${file}` : entry.endsWith(suffix) ? `${dir}/${entry}` : null;
      const text = rel && read(root, rel);
      if (rel && text && isGenerated(text)) found.push(rel);
    }
    if (a.rules && isGenerated(read(root, a.rules.path) ?? '')) found.push(a.rules.path);
  }
  return found;
}

function firstDifference(expected: string, actual: string): string {
  const e = expected.split('\n');
  const a = actual.split('\n');
  for (let i = 0; i < Math.max(e.length, a.length); i++) {
    if (e[i] !== a[i]) return `line ${i + 1}: expected ${JSON.stringify(e[i] ?? '<end of file>')}, found ${JSON.stringify(a[i] ?? '<end of file>')}`;
  }
  return 'contents differ';
}

export function check(root: string, adapters: Adapter[] = DEFAULT_ADAPTERS): Problem[] {
  const planned = plan(loadSource(root), adapters);
  const problems: Problem[] = [];
  for (const [file, expected] of planned) {
    const actual = read(root, file);
    if (actual === null) problems.push({ file, kind: 'missing', detail: 'not generated yet' });
    else if (!isGenerated(actual)) problems.push({ file, kind: 'handwritten', detail: 'file exists without the generated marker' });
    else if (actual !== expected) problems.push({ file, kind: 'changed', detail: firstDifference(expected, actual) });
  }
  for (const file of generatedOnDisk(root, adapters)) {
    if (!planned.has(file)) problems.push({ file, kind: 'extra', detail: 'generated file has no source any more' });
  }
  return problems;
}

/** Writes every projection. Refuses to overwrite a file without the marker unless it is in `adopt`. */
export function build(root: string, adapters: Adapter[] = DEFAULT_ADAPTERS, adopt: Set<string> = new Set()): string[] {
  const planned = plan(loadSource(root), adapters);
  for (const file of planned.keys()) {
    const actual = read(root, file);
    if (actual !== null && !isGenerated(actual) && !adopt.has(file)) {
      throw new SourceError(`${file} exists and was not generated by skillcast; run "skillcast init" to import it`);
    }
  }
  const changed: string[] = [];
  for (const [file, content] of planned) {
    if (read(root, file) === content) continue;
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), content);
    changed.push(file);
  }
  for (const file of generatedOnDisk(root, adapters)) {
    if (planned.has(file)) continue;
    rmSync(join(root, file));
    changed.push(`${file} (removed)`);
  }
  return changed;
}

type Imported = { description: string; extra: Map<string, string>; body: string; from: string };

/** Imports existing CLAUDE.md, AGENTS.md and skills into .skillcast/, then builds. Conflicts abort. */
export function init(root: string, adapters: Adapter[] = DEFAULT_ADAPTERS): { imported: string[]; built: string[] } {
  if (existsSync(join(root, SOURCE_DIR))) throw new SourceError(`${SOURCE_DIR}/ already exists`);
  const conflicts: string[] = [];
  const imported: string[] = [];

  let rules: { body: string; from: string } | undefined;
  for (const a of adapters) {
    const text = a.rules && read(root, a.rules.path);
    if (!a.rules || !text || isGenerated(text)) continue;
    const body = normalize(text);
    if (rules && rules.body !== body) conflicts.push(`${rules.from} and ${a.rules.path} differ; make them equal or delete one, then run init again`);
    rules ??= { body, from: a.rules.path };
    imported.push(a.rules.path);
  }

  const skills = new Map<string, Imported>();
  for (const a of adapters.filter((x) => x.skillGlob.file)) {
    const dir = a.skillGlob.dir;
    if (!existsSync(join(root, dir))) continue;
    for (const name of readdirSync(join(root, dir)).sort()) {
      const from = `${dir}/${name}/${a.skillGlob.file}`;
      const text = read(root, from);
      if (!text || isGenerated(text)) continue;
      const fm = parseFrontmatter(text, from);
      if (!fm?.fields.get('description')) {
        conflicts.push(`${from}: no frontmatter description, cannot import`);
        continue;
      }
      const extra = new Map([...fm.fields].filter(([k]) => k !== 'name' && k !== 'description'));
      const skill = { description: unquote(fm.fields.get('description')!), extra, body: normalize(fm.body), from };
      const prev = skills.get(name);
      if (prev && (prev.description !== skill.description || prev.body !== skill.body)) {
        conflicts.push(`${prev.from} and ${from} describe skill "${name}" differently`);
      } else if (prev) {
        for (const [k, v] of extra) prev.extra.set(k, v);
      } else skills.set(name, skill);
      imported.push(from);
    }
  }
  if (conflicts.length) throw new SourceError(`init stopped, nothing was written:\n- ${conflicts.join('\n- ')}`);

  mkdirSync(join(root, SOURCE_DIR, 'skills'), { recursive: true });
  if (rules) writeFileSync(join(root, SOURCE_DIR, 'rules.md'), rules.body);
  for (const [name, s] of skills) {
    const extra = [...s.extra].map(([k, v]) => `${k}: ${v}`);
    const head = ['---', `name: ${name}`, `description: ${JSON.stringify(s.description)}`, ...extra, '---', ''].join('\n');
    writeFileSync(join(root, SOURCE_DIR, 'skills', `${name}.md`), `${head}${s.body}`);
  }
  try {
    return { imported, built: build(root, adapters, new Set(imported)) };
  } catch (e) {
    rmSync(join(root, SOURCE_DIR), { recursive: true, force: true });
    if (e instanceof SourceError) throw new SourceError(`init stopped, nothing was written:\n- ${e.message}`);
    throw e;
  }
}
