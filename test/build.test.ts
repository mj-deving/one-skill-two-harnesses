import { describe, expect, test } from 'bun:test';
import { readdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { build, check } from '../src/core';
import { copyExample, EXAMPLE, get, put, skill, tempRepo } from './helpers';

function walk(dir: string, base = dir): string[] {
  return readdirSync(dir).flatMap((e) => {
    const p = join(dir, e);
    return statSync(p).isDirectory() ? walk(p, base) : [relative(base, p).split(sep).join('/')];
  });
}

describe('build', () => {
  test('ISC-2: projections match the committed golden files byte for byte', () => {
    const root = copyExample();
    const golden = walk(EXAMPLE).filter((f) => !f.startsWith('.skillcast/')).sort();
    for (const f of golden) rmSync(join(root, f));
    build(root);
    expect(walk(root).filter((f) => !f.startsWith('.skillcast/')).sort()).toEqual(golden);
    for (const f of golden) expect(get(root, f)).toBe(readFileSync(join(EXAMPLE, f), 'utf8'));
  });

  test('ISC-2: every SKILL.md carries name and description; cursor rule carries description, globs, alwaysApply', () => {
    for (const dir of ['.claude/skills', '.agents/skills']) {
      for (const name of readdirSync(join(EXAMPLE, dir))) {
        const text = get(EXAMPLE, `${dir}/${name}/SKILL.md`);
        expect(text).toStartWith(`---\nname: ${name}\ndescription: "`);
      }
    }
    expect(get(EXAMPLE, '.cursor/rules/test-layout.mdc')).toStartWith('---\ndescription: "Where and how to write tests. Use when asked to add, write or extend tests."\nglobs: "**/*.spec.ts"\nalwaysApply: false\n---\n');
  });

  test('ISC-3: harness blocks land only in their own projection', () => {
    expect(get(EXAMPLE, 'CLAUDE.md')).toContain('Claude Code: use the skills');
    expect(get(EXAMPLE, 'CLAUDE.md')).not.toContain('Codex: use the skills');
    expect(get(EXAMPLE, 'AGENTS.md')).toContain('Codex: use the skills');
    expect(get(EXAMPLE, 'AGENTS.md')).not.toContain('Claude Code: use the skills');
    for (const f of ['CLAUDE.md', 'AGENTS.md']) expect(get(EXAMPLE, f)).toContain('Keep changes small');
  });

  test('ISC-3: skill-level blocks work for all three harnesses', () => {
    const body = 'shared\n<!-- only:cursor -->\ncursor only\n<!-- /only -->\n<!-- only:codex -->\ncodex only\n<!-- /only -->\n';
    const root = tempRepo({ '.skillcast/skills/s.md': skill('s', body) });
    build(root);
    expect(get(root, '.cursor/rules/s.mdc')).toContain('cursor only');
    expect(get(root, '.cursor/rules/s.mdc')).not.toContain('codex only');
    expect(get(root, '.agents/skills/s/SKILL.md')).toContain('codex only');
    expect(get(root, '.claude/skills/s/SKILL.md')).not.toContain('only');
  });

  test('ISC-4: every file names its source, and a second build changes no byte', () => {
    const root = copyExample();
    expect(build(root)).toEqual([]);
    expect(get(root, 'AGENTS.md')).toStartWith('<!-- generated by skillcast from .skillcast/rules.md.');
    expect(get(root, '.agents/skills/error-codes/SKILL.md')).toContain('generated by skillcast from .skillcast/skills/error-codes.md.');
    expect(check(root)).toEqual([]);
  });

  test('ISC-4: CRLF source gives the same bytes as LF source', () => {
    const lf = tempRepo({ '.skillcast/rules.md': 'a\nb\n' });
    const crlf = tempRepo({ '.skillcast/rules.md': 'a\r\nb\r\n' });
    build(lf);
    build(crlf);
    expect(get(crlf, 'CLAUDE.md')).toBe(get(lf, 'CLAUDE.md'));
  });

  test('ISC-14: a hand-written file at a target path stops the build and names init', () => {
    const root = tempRepo({ '.skillcast/rules.md': 'rules\n', 'CLAUDE.md': 'my own notes\n' });
    expect(() => build(root)).toThrow(/CLAUDE.md exists and was not generated by skillcast; run "skillcast init"/);
    expect(get(root, 'CLAUDE.md')).toBe('my own notes\n');
  });

  test('removing a skill from the source removes its generated files', () => {
    const root = copyExample();
    rmSync(join(root, '.skillcast/skills/error-codes.md'));
    const changed = build(root);
    expect(changed).toContain('.cursor/rules/error-codes.mdc (removed)');
    expect(check(root)).toEqual([]);
  });

  test('a hand-written skill next to generated ones is left alone', () => {
    const root = copyExample();
    put(root, '.claude/skills/mine/SKILL.md', skill('mine'));
    build(root);
    expect(get(root, '.claude/skills/mine/SKILL.md')).toBe(skill('mine'));
  });
});
