/**
 * Runs every task in both harnesses and three variants, scores each run with the task's own
 * deterministic check and writes results/<stamp>/runs.jsonl plus summary.md.
 *
 * Variants: none (no skill files), copy (a plain hand-maintained copy without marker),
 * generated (the files skillcast builds from examples/basic/.skillcast).
 */
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import type { Task } from './types';

const ROOT = join(import.meta.dir, '..');
const EXAMPLE = join(ROOT, 'examples/basic');
const harnesses = ['claude', 'codex'] as const;
type Harness = (typeof harnesses)[number];
const variants = ['none', 'copy', 'generated'] as const;
type Variant = (typeof variants)[number];

const arg = (flag: string) => process.argv.find((a) => a.startsWith(`--${flag}=`))?.split('=')[1];
const trials = Number(arg('trials') ?? 3);
const controlTrials = Number(arg('control-trials') ?? 1);
const parallel = Number(arg('parallel') ?? 4);
const only = arg('task');
const set = arg('set'); // "heldout" | "dev" | undefined
const dry = process.argv.includes('--dry');
const codexModel = arg('codex-model') ?? 'gpt-5.6-sol';

const tasks: Task[] = [];
for (const f of readdirSync(join(import.meta.dir, 'tasks')).sort()) tasks.push((await import(`./tasks/${f}`)).default);

const HARNESS_FILES: Record<Harness, (path: string) => boolean> = {
  claude: (p) => p === 'CLAUDE.md' || p.startsWith('.claude/'),
  codex: (p) => p === 'AGENTS.md' || p.startsWith('.agents/'),
};
const MARKER_LINE = /^<!-- generated by skillcast from .*-->\n\n?/m;

function exampleFiles(): Map<string, string> {
  const out = new Map<string, string>();
  const walk = (dir: string, rel = '') => {
    for (const e of readdirSync(join(dir, rel), { withFileTypes: true })) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(dir, r);
      else out.set(r, readFileSync(join(dir, r), 'utf8'));
    }
  };
  walk(EXAMPLE);
  return out;
}

function harnessFiles(h: Harness, v: Variant): Map<string, string> {
  if (v === 'none') return new Map();
  const files = [...exampleFiles()].filter(([p]) => HARNESS_FILES[h](p));
  return new Map(v === 'generated' ? files : files.map(([p, t]) => [p, t.replace(MARKER_LINE, '')]));
}

function sh(cmd: string[], cwd: string) {
  return Bun.spawnSync(cmd, { cwd, stdout: 'pipe', stderr: 'pipe' });
}

/** Subscription auth only: strip API keys and the nested-session guard. */
function cleanEnv(): Record<string, string> {
  const env = { ...process.env } as Record<string, string>;
  for (const k of ['ANTHROPIC_API_KEY', 'ANTHROPIC_AUTH_TOKEN', 'OPENAI_API_KEY', 'CLAUDECODE', 'CLAUDE_CODE_ENTRYPOINT']) delete env[k];
  return env;
}

function command(h: Harness, dir: string, prompt: string): string[] {
  if (h === 'claude') {
    const tools = 'Read Write Edit Glob Grep Skill Bash(bun test:*) Bash(bun run:*)';
    return ['claude', '-p', prompt, '--permission-mode', 'acceptEdits', '--allowedTools', tools, '--setting-sources', 'project', '--output-format', 'json'];
  }
  return ['codex', 'exec', '--skip-git-repo-check', '--ignore-user-config', '--sandbox', 'workspace-write', '--json', '-m', codexModel, '-C', dir, prompt];
}

function modelOf(h: Harness, stdout: string): string {
  if (h === 'claude') {
    try {
      return Object.keys(JSON.parse(stdout).modelUsage ?? {}).join('+') || 'unknown';
    } catch {
      return 'unknown';
    }
  }
  return codexModel;
}

const version = (h: Harness) => sh([h, '--version'], ROOT).stdout.toString().trim();
const versions = Object.fromEntries(harnesses.map((h) => [h, version(h)]));

type Job = { task: Task; harness: Harness; variant: Variant; trial: number };
const jobs: Job[] = [];
for (const task of tasks) {
  if (only && task.id !== only) continue;
  if (set === 'heldout' && !task.heldout) continue;
  if (set === 'dev' && task.heldout) continue;
  for (const harness of harnesses)
    for (const variant of variants)
      for (let trial = 1; trial <= (variant === 'none' ? controlTrials : trials); trial++) jobs.push({ task, harness, variant, trial });
}

const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
const outDir = join(ROOT, 'results', stamp);
console.log(`${jobs.length} runs, ${parallel} at a time${dry ? ' (dry run, no agents started)' : ''}`);

async function runJob(job: Job) {
  const dir = mkdtempSync(join(tmpdir(), `skillcast-bench-${job.task.id}-`));
  for (const [rel, text] of [...Object.entries(job.task.files), ...harnessFiles(job.harness, job.variant)]) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  }
  sh(['git', 'init', '-q'], dir);
  sh(['git', '-c', 'user.name=bench', '-c', 'user.email=bench@example.invalid', 'commit', '-qam', 'fixture', '--allow-empty'], dir);
  sh(['git', 'add', '-A'], dir);
  sh(['git', '-c', 'user.name=bench', '-c', 'user.email=bench@example.invalid', 'commit', '-qm', 'fixture'], dir);
  const started = Date.now();
  let stdout = '';
  let exitCode = 0;
  if (!dry) {
    const p = Bun.spawn(command(job.harness, dir, job.task.prompt), { cwd: dir, env: cleanEnv(), stdout: 'pipe', stderr: 'ignore', stdin: 'ignore', timeout: 600_000 });
    stdout = await new Response(p.stdout).text();
    exitCode = await p.exited;
  }
  const verdict = dry ? { pass: false, reason: 'dry run' } : await job.task.check(dir);
  return {
    task: job.task.id,
    skill: job.task.skill,
    heldout: job.task.heldout,
    harness: job.harness,
    variant: job.variant,
    trial: job.trial,
    pass: verdict.pass,
    reason: verdict.reason,
    agentExit: exitCode,
    seconds: Math.round((Date.now() - started) / 1000),
    cli: versions[job.harness],
    model: dry ? 'none' : modelOf(job.harness, stdout),
  };
}

type Row = Awaited<ReturnType<typeof runJob>>;
const rows: Row[] = [];
mkdirSync(outDir, { recursive: true });
const queue = [...jobs];
await Promise.all(
  Array.from({ length: parallel }, async () => {
    for (let job = queue.shift(); job; job = queue.shift()) {
      const row = await runJob(job);
      rows.push(row);
      writeFileSync(join(outDir, 'runs.jsonl'), rows.map((r) => JSON.stringify(r)).join('\n') + '\n');
      console.log(`${row.pass ? 'PASS' : 'FAIL'} ${row.harness} ${row.variant} ${row.task} #${row.trial} (${row.seconds}s) ${row.pass ? '' : row.reason}`);
    }
  }),
);

rows.sort((a, b) => `${a.task}${a.harness}${a.variant}${a.trial}`.localeCompare(`${b.task}${b.harness}${b.variant}${b.trial}`));
writeFileSync(join(outDir, 'runs.jsonl'), rows.map((r) => JSON.stringify(r)).join('\n') + '\n');

const rate = (rs: Row[]) => `${rs.filter((r) => r.pass).length}/${rs.length}`;
const pick = (h: string, v: string, held?: boolean) => rows.filter((r) => r.harness === h && r.variant === v && (held === undefined || r.heldout === held));
const lines = [
  `# Bench run ${stamp}`,
  '',
  `Tasks: ${new Set(rows.map((r) => r.task)).size} · trials per task: ${trials} (control: ${controlTrials}) · runs: ${rows.length}`,
  '',
  ...harnesses.map((h) => `- ${h}: ${versions[h]}, model ${[...new Set(rows.filter((r) => r.harness === h).map((r) => r.model))].join(', ')}`),
  '',
  '| harness | variant | all tasks | dev tasks | held-out tasks |',
  '|---|---|---|---|---|',
  ...harnesses.flatMap((h) => variants.map((v) => `| ${h} | ${v} | ${rate(pick(h, v))} | ${rate(pick(h, v, false))} | ${rate(pick(h, v, true))} |`)),
  '',
  '## Failures',
  '',
  ...(rows.some((r) => !r.pass) ? rows.filter((r) => !r.pass).map((r) => `- ${r.harness} ${r.variant} ${r.task} #${r.trial}: ${r.reason}`) : ['none']),
  '',
];
writeFileSync(join(outDir, 'summary.md'), lines.join('\n'));
console.log(`\nwrote ${join('results', stamp)}/summary.md`);
if (dry) console.log('dry run: results folder is a format check only');
